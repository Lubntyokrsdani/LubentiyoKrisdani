private void setupTable() {

    DefaultTableModel model = new DefaultTableModel(
        new Object[][]{},
        new String[]{
            "ID",
            "Product Code",
            "Product Name",
            "Category",
            "Price",
            "Stock",
            "Unit",
            "Status"
        }
    ) {
        @Override
        public boolean isCellEditable(int row, int column) {
            return false;
        }
    };

    TabelData.setModel(model);
    TabelData.setRowHeight(30);
}
private void loadProducts() {

    try {

        ProductDAO dao = SpringContext.getBean(ProductDAO.class);

        List<Product> products = dao.findAll();

        DefaultTableModel model =
                (DefaultTableModel) TabelData.getModel();

        model.setRowCount(0);

        for (Product p : products) {

            model.addRow(new Object[]{
                p.getId(),
                p.getProductCode(),
                p.getProductName(),
                p.getCategory().getCategoryName(),
                p.getPrice(),
                p.getStock(),
                p.getUnit(),
                p.getStatus()
            });
        }

    } catch (Exception e) {

        JOptionPane.showMessageDialog(
                this,
                "Failed to load products: " + e.getMessage()
        );
    }
}
private void searchProducts() {

    try {

        String keyword = TxtSearching.getText().trim();

        ProductDAO dao = SpringContext.getBean(ProductDAO.class);

        List<Product> products = dao.search(keyword);

        DefaultTableModel model =
                (DefaultTableModel) TabelData.getModel();

        model.setRowCount(0);

        for (Product p : products) {

            model.addRow(new Object[]{
                p.getId(),
                p.getProductCode(),
                p.getProductName(),
                p.getCategory().getCategoryName(),
                p.getPrice(),
                p.getStock(),
                p.getUnit(),
                p.getStatus()
            });
        }

    } catch (Exception e) {

        JOptionPane.showMessageDialog(
                this,
                "Search failed: " + e.getMessage()
        );
    }
}
