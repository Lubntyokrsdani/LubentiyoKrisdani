    private void TombolSubmitLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_TombolSubmitLoginActionPerformed
        String username = UsernameForm.getText().trim();
        String password = PasswordForm.getText().trim();

        if (username.isEmpty() || password.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Username dan password wajib diisi!");
            return;
        }

        String url = "jdbc:mysql://localhost:3306/orderflow_db";
        String dbUser = "root";
        String dbPassword = "";

        String sql = "SELECT * FROM user WHERE username = ? AND password = ?";

        try {
            java.sql.Connection conn = java.sql.DriverManager.getConnection(
                    url, dbUser, dbPassword);

            java.sql.PreparedStatement pst = conn.prepareStatement(sql);

            pst.setString(1, username);
            pst.setString(2, password);

            java.sql.ResultSet rs = pst.executeQuery();

            if (rs.next()) {
                javax.swing.JOptionPane.showMessageDialog(this,
                        "Login berhasil! Selamat Datang, " + username);

            } else {
                javax.swing.JOptionPane.showMessageDialog(this,
                        "Username atau password salah!");
            }

            rs.close();
            pst.close();
            conn.close();

        } catch (java.sql.SQLException e) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Koneksi database gagal: " + e.getMessage());
        }
    }//GEN-LAST:event_TombolSubmitLoginActionPerformed

